//! The app's adaptive launcher icon in android/res/ (docs/android.md): "OKB" in plain stroked letters drawn here as
//! vector paths (no font, no game artwork) on a dark red background.
//!
//! `cargo test --test android_icon` checks that the committed files are what this writes;
//! `OKB_WRITE_ICON=1 cargo test --test android_icon` writes them (after a change here).
//!
//! Output (committed; android/build.sh compiles res/ with aapt2):
//!   mipmap-anydpi-v26/ic_launcher.xml        the adaptive icon: background, foreground, monochrome (themed icons)
//!   drawable/ic_launcher_background.xml      dark red with a darker lower half
//!   drawable/ic_launcher_foreground.xml      the letters with a shadow
//!   drawable/ic_launcher_monochrome.xml      the letters alone
//! The vector canvas is the adaptive icon's 108 x 108 dp; the letters stay inside the 66 dp safe circle.
use std::fmt::Write as _;
use std::path::Path;

/// the letters' centre lines (stroked), on a 108 x 108 canvas: cap height 39..69, O K B left to right
const LETTERS: [&str; 7] = [
    // O: a stadium (round top and bottom, straight sides)
    "M24,46.5 A7.5,7.5 0 0 1 39,46.5 V61.5 A7.5,7.5 0 0 1 24,61.5 Z",
    // K: the stem, the upper arm, the leg (from the arm's middle; both kept inside the stem's outline)
    "M47,39 V69",
    "M60,39 L49.5,52.7",
    "M54.5,46 L60,69",
    // B: the stem, the upper bowl, the (wider) lower bowl
    "M67.5,39 V69",
    "M67.5,39 H76 A7.25,7.25 0 0 1 76,53.5 H67.5",
    "M67.5,53.5 H77 A7.75,7.75 0 0 1 77,69 H67.5",
];
const STROKE: f64 = 5.5;
/// the group centred on the canvas and scaled into the safe circle
const SCALE: f64 = 0.86;
/// (the offsets are printed with f64 Display: keep them exactly representable in a few decimals, or the XML gets noisy)
const SHIFT: (f64, f64) = (54.0 - (24.0 + 84.75) / 2.0, 0.0);

// (an XML comment may not hold "--", so no command line here)
const HEADER: &str = "<!-- Generated by tests/android_icon.rs; edit that test, not this file. -->\n";

fn group(colour: &str, dx: f64, dy: f64) -> String {
    let mut out = format!(
        "    <group android:pivotX=\"54\" android:pivotY=\"54\" android:scaleX=\"{SCALE}\" android:scaleY=\"{SCALE}\" \
         android:translateX=\"{}\" android:translateY=\"{}\">\n",
        SHIFT.0 + dx,
        SHIFT.1 + dy
    );
    for d in LETTERS {
        writeln!(
            out,
            "        <path android:pathData=\"{d}\" android:strokeColor=\"{colour}\" android:strokeWidth=\"{STROKE}\" \
             android:strokeLineCap=\"square\" android:strokeLineJoin=\"miter\" android:fillColor=\"#00000000\" />"
        )
        .unwrap();
    }
    out + "    </group>"
}

fn vector(body: &str) -> String {
    format!(
        "{HEADER}<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n    android:width=\"108dp\" \
         android:height=\"108dp\" android:viewportWidth=\"108\" android:viewportHeight=\"108\">\n{body}\n</vector>\n"
    )
}

/// (path under android/res, contents)
fn files() -> Vec<(&'static str, String)> {
    vec![
        (
            "drawable/ic_launcher_background.xml",
            vector(
                "    <path android:pathData=\"M0,0 H108 V108 H0 Z\" android:fillColor=\"#7A0E0E\" />\n    \
                 <path android:pathData=\"M0,62 H108 V108 H0 Z\" android:fillColor=\"#5C0909\" />",
            ),
        ),
        ("drawable/ic_launcher_foreground.xml", vector(&(group("#3A0303", 1.2, 1.6) + "\n" + &group("#F4EEEA", 0.0, 0.0)))),
        ("drawable/ic_launcher_monochrome.xml", vector(&group("#FFFFFFFF", 0.0, 0.0))),
        (
            "mipmap-anydpi-v26/ic_launcher.xml",
            format!(
                "{HEADER}<adaptive-icon xmlns:android=\"http://schemas.android.com/apk/res/android\">\n    \
                 <background android:drawable=\"@drawable/ic_launcher_background\" />\n    \
                 <foreground android:drawable=\"@drawable/ic_launcher_foreground\" />\n    \
                 <monochrome android:drawable=\"@drawable/ic_launcher_monochrome\" />\n</adaptive-icon>\n"
            ),
        ),
    ]
}

#[test]
fn android_icon_is_generated() {
    let res = Path::new(env!("CARGO_MANIFEST_DIR")).join("android/res");
    let write = open_kumite_beast::base::env::var_os("WRITE_ICON").is_some_and(|v| v == "1");
    for (rel, text) in files() {
        let path = res.join(rel);
        if write {
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, &text).unwrap();
            println!("{}", path.display());
        } else {
            let committed = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e} (OKB_WRITE_ICON=1 regenerates it)", path.display()));
            assert!(committed == text, "{} is not what tests/android_icon.rs writes (OKB_WRITE_ICON=1 regenerates it)", path.display());
        }
    }
}
