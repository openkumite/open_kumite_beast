#!/bin/bash
# Writes THIRD_PARTY_NOTICES.md: every crate that a shipped build links (all targets, default features plus
# netplay-webrtc, the union of the desktop, web and Android builds), with its license and source. The project's own
# crates are left out: path crates and the converter crates (git dependencies on github.com/openkumite). Run it after
# any change to the dependencies (CONTRIBUTING.md, "Checks").
#
#   tools/third_party_notices.sh
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=THIRD_PARTY_NOTICES.md
FEATURES=netplay-webrtc

# name|version|license|repository, one row per crate version, sorted by name; "/" in a license reads as OR.
rows=$(cargo tree -e normal,build --target all --features "$FEATURES" --prefix none --format '{p}|{l}|{r}' \
    | sed -e 's/ (\*)$//' -e 's/ (proc-macro)|/|/' \
    | grep -v -e '^[^|]* (/' -e '^[^|]* (https://github\.com/openkumite/' \
    | sed -e 's/^\([^ ]*\) v\([^|]*\)|/\1|\2|/' \
    | awk -F'|' -v OFS='|' '{ gsub(/ *\/ */, " OR ", $3); print }' \
    | LC_ALL=C sort -t'|' -k1,1 -k2,2V -u)

# A license expression with the operands of a plain OR list sorted, so equal expressions count together.
summary=$(printf '%s\n' "$rows" | awk -F'|' '
{
    l = $3
    if (l !~ /[()]/ && l !~ / AND /) {
        n = split(l, a, / OR /)
        for (i = 2; i <= n; i++) { v = a[i]; j = i - 1; while (j > 0 && a[j] > v) { a[j + 1] = a[j]; j-- } a[j + 1] = v }
        l = a[1]; for (i = 2; i <= n; i++) l = l " OR " a[i]
    }
    c[l]++
}
END { for (l in c) printf "%d|%s\n", c[l], l }' | LC_ALL=C sort -t'|' -k1,1nr -k2,2 \
    | awk -F'|' '{ printf "- %s: %d crate%s\n", $2, $1, ($1 == 1 ? "" : "s") }')

count=$(printf '%s\n' "$rows" | wc -l | tr -d ' ')

{
    cat <<HEAD
# Third-party notices

OpenKumiteBeast is distributed under the MIT License (see \`LICENSE\`). Its builds include the third-party code listed
below, each under its own license. The list covers every target and the \`$FEATURES\` feature, so it is the union of
the desktop, web and Android builds; a build without that feature links a subset. The license texts and copyright
notices are in each crate's source package (crates.io / the linked repository); a binary distribution must ship them
alongside (for example generated with \`cargo about\`).

This file is generated by \`tools/third_party_notices.sh\` from
\`cargo tree -e normal,build --target all --features $FEATURES\` ($count crates); rerun it after changing dependencies.

## File-level copyleft

These crates are under the Mozilla Public License 2.0 and are used unmodified; their source is available
from crates.io and the linked repositories: $(printf '%s\n' "$rows" | awk -F'|' '$3 == "MPL-2.0" { printf "%s`%s`", s, $1; s = ", " }').

## Notable licenses

- \`webpki-roots\` (CDLA-Permissive-2.0): the Mozilla root certificate data it carries is under the Community Data
  License Agreement – Permissive 2.0; a distribution of the data must include the agreement text or a link to it
  (https://cdla.dev/permissive-2-0/).
- \`ring\` (Apache-2.0 AND ISC): parts of it derive from BoringSSL and OpenSSL; its \`LICENSE\` file carries those
  notices, which a binary distribution must reproduce.

## Licenses used

$summary

## Rust crates

| Crate | Version | License | Source |
|---|---|---|---|
HEAD
    printf '%s\n' "$rows" | awk -F'|' '{ printf "| %s | %s | %s | %s |\n", $1, $2, $3, $4 }'
} > "$OUT"
